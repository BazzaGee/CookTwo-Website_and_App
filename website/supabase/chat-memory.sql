-- Chat memory schema for the cooktwo.com site + Kitchen Tool assistants.
-- Apply once in the Supabase SQL editor for the project referenced by
-- SUPABASE_URL. The Pages Functions use the service-role key, which bypasses
-- RLS; no anon policies are required.

create table if not exists public.chat_sessions (
  id uuid primary key,
  first_page text,
  mode text,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.chat_sessions(id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  page_url text,
  mode text,
  model text,
  created_at timestamptz not null default now()
);

create index if not exists chat_messages_session_created_idx
  on public.chat_messages (session_id, created_at desc);

create index if not exists chat_messages_session_mode_created_idx
  on public.chat_messages (session_id, mode, created_at desc);

alter table public.chat_sessions enable row level security;
alter table public.chat_messages enable row level security;
